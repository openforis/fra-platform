export type FAOSTATRow = {
  'Area Code (M49)': string
  Year: string
  Value: string
}

export type FAOSTATApiResponse = {
  data: Array<FAOSTATRow>
}

const _fetchRaw = async (): Promise<FAOSTATApiResponse> => {
  const token = process.env.FAOSTAT_AUTH_TOKEN
  if (!token) throw new Error('FAOSTAT_AUTH_TOKEN is not set in the environment')

  const response = await axios.get<FAOSTATApiResponse>(FAOSTAT_API_URL, {
    headers: { Authorization: `Bearer ${token}` },
  })

  return response.data
}

export const getFAOStat = async (): Promise<Array<FAOSTATRow>> => {
  const raw = await _fetchRaw()

  if (process.argv.includes('--save-file')) {
    const outPath = path.join(__dirname, 'FAOSTAT_data.json')
    fs.writeFileSync(outPath, JSON.stringify(raw, null, 2))
    Logger.info(`Saved ${raw.data.length} rows to ${outPath}`)
  }

  return raw.data
}
